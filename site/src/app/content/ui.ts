/**
 * The product page's short UI strings, moved from the Astro site unchanged
 * (`src/i18n/ui.ts` there).
 *
 * Moved rather than rewritten: this is 445 keys in five languages, it is the
 * site's actual payload, and a rewrite would be a translation project dressed
 * as a migration (enigma2_player-n5j).
 *
 * REMOVED on 2026-10-09, with reasons rather than silently (the old
 * repository carried 127 unread keys - enigma2_player_source-gwf):
 *  - the four `*.loading` strings, because nothing loads any more: the data is
 *    baked in at build time, so there is no state between "no data" and "the
 *    data" (enigma2_player-n5j);
 *  - `auth.*`, `account.*` and `buy.*`, about forty strings for a login, an
 *    account view and a checkout. None of it is rendered here: the licence
 *    server renders its own shop and account pages inside the frame, with its
 *    own texts (its ADR-0005). A second set would mean maintaining German for
 *    a page nobody sees;
 *  - `placeholder.body` and `pricing.cta`, left from the Astro placeholder
 *    route and from a button that now reads `nav.buy`.
 *
 * If the shop is ever rendered on this site instead of framed, they come back
 * out of git - cheaper than carrying them in five languages meanwhile.
 *
 * The language list is NOT declared here. It lives in `../i18n/locales.ts`,
 * which is the whole point of that file: the Astro site kept the list in three
 * places and one of them was wrong, which is how `/fr` and `/it` were served
 * as German (enigma2_player-w83).
 */
